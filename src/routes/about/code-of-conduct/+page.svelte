<Section title="Code of Conduct">
    <div class="border-t border-base-300 pt-3 space-y-8">
        <Section title="Community Pledge">
            <p class="leading-relaxed">
                In the interest of fostering an open and welcoming environment, contributors and maintainers pledge to make participation in the ACROSS project
                and the community a harassment-free experience for everyone, treating all with equal dignity and respect.
            </p>
        </Section>

        <Section title="Community Standards">
            <p class="leading-relaxed">Examples of behavior that contributes to creating a positive environment include:</p>
            <ul class="list-disc list-inside space-y-1 ml-2 leading-relaxed">
                <li>Using welcoming and professional language</li>
                <li>Being respectful of differing viewpoints and experiences</li>
                <li>Gracefully accepting constructive criticism</li>
                <li>Focusing on what is best for the community</li>
                <li>Showing empathy towards other community members</li>
            </ul>
            <p class="leading-relaxed">Examples of unacceptable behavior by participants include:</p>
            <ul class="list-disc list-inside space-y-1 ml-2 leading-relaxed">
                <li>The use of sexualized language or imagery and unwelcome sexual attention or advances</li>
                <li>Trolling, insulting/derogatory comments, and personal or political attacks</li>
                <li>Public or private harassment</li>
                <li>Publishing others' private information, such as a physical or electronic address, without explicit permission</li>
                <li>Other conduct which could reasonably be considered inappropriate in a professional setting</li>
            </ul>
        </Section>

        <Section title="Maintainer Responsibilities">
            <p class="leading-relaxed">
                Project maintainers are responsible for clarifying the standards of acceptable behavior and are expected to take appropriate and fair corrective
                action in response to any instances of unacceptable behavior.
            </p>
            <p class="leading-relaxed">
                Project maintainers have the right and responsibility to remove, edit, or reject comments, commits, code, wiki edits, issues, and other
                contributions that are not aligned to this Code of Conduct, or to ban temporarily or permanently any contributor for other behaviors that they
                deem inappropriate, threatening, offensive, or harmful.
            </p>
        </Section>

        <Section title="Scope">
            <p class="leading-relaxed">
                This Code of Conduct applies within all project spaces, and it also applies when an individual is representing the project or its community in
                public spaces. Examples of representing a project or community include using an official project e-mail address, posting via an official social
                media account, or acting as an appointed representative at an online or offline event. Representation of a project may be further defined and
                clarified by project maintainers.
            </p>
        </Section>

        <Section title="Enforcement">
            <p class="leading-relaxed">
                Instances of abusive, harassing, or otherwise unacceptable behavior may be reported to NASA ACROSS. All complaints will be reviewed and
                investigated and will result in a response that is deemed necessary and appropriate to the circumstances. The project team is obligated to
                maintain confidentiality with regard to the reporter of an incident. Further details of specific enforcement policies may be posted separately.
            </p>
            <p class="leading-relaxed">
                Project maintainers who do not follow or enforce the Code of Conduct in good faith may face temporary or permanent repercussions as determined
                by other members of the project's leadership.
            </p>
        </Section>

